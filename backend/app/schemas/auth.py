import uuid
from datetime import datetime

from pydantic import BaseModel, Field, field_validator


class DeviceAuthRequest(BaseModel):
    device_id: str = Field(min_length=16, max_length=128, pattern=r"^[A-Za-z0-9\-_]+$",
                           description="Random id generated by the app on first launch")
    device_secret: str = Field(min_length=32, max_length=256,
                               description="Random secret (>=256 bits) kept in the device keystore")
    platform: str = Field("other", pattern="^(android|ios|web|other)$")
    name: str | None = Field(default=None, max_length=100)


class RefreshRequest(BaseModel):
    refresh_token: str = Field(min_length=10)


class TokenPair(BaseModel):
    access_token: str
    refresh_token: str
    token_type: str = "bearer"
    expires_in: int = Field(description="Access token lifetime in seconds")


class DeviceAuthResponse(TokenPair):
    created: bool = Field(description="True when this call created the device's account")


class Preferences(BaseModel):
    languages: list[str] = []
    audio_quality: str = "high"
    allow_explicit: bool = True


class PreferencesUpdate(BaseModel):
    languages: list[str] | None = Field(default=None, max_length=10)
    audio_quality: str | None = Field(default=None, pattern="^(low|medium|high|very_high)$")
    allow_explicit: bool | None = None

    @field_validator("languages")
    @classmethod
    def clean_languages(cls, v: list[str] | None) -> list[str] | None:
        if v is None:
            return v
        out = []
        for lang in v:
            lang = lang.strip().title()
            if not lang.replace(" ", "").isalpha() or len(lang) > 50:
                raise ValueError(f"Invalid language: {lang!r}")
            if lang not in out:
                out.append(lang)
        return out


class NotificationPrefs(BaseModel):
    new_releases: bool = True
    recommendations: bool = True
    followed_artists: bool = True


class NotificationPrefsUpdate(BaseModel):
    new_releases: bool | None = None
    recommendations: bool | None = None
    followed_artists: bool | None = None


class UserOut(BaseModel):
    id: uuid.UUID
    display_name: str
    avatar_url: str | None = None
    country: str | None = None
    created_at: datetime
    preferences: Preferences
    notifications: NotificationPrefs


class ProfileUpdate(BaseModel):
    display_name: str | None = Field(default=None, min_length=1, max_length=100)
    avatar_url: str | None = Field(default=None, max_length=1024)
    country: str | None = Field(default=None, min_length=2, max_length=2)


class DeviceRegister(BaseModel):
    installation_id: str = Field(min_length=8, max_length=128)
    platform: str = Field(pattern="^(android|ios|web|other)$")
    name: str | None = Field(default=None, max_length=100)
    push_token: str | None = Field(default=None, max_length=512)


class DeviceOut(BaseModel):
    id: uuid.UUID
    installation_id: str
    platform: str
    name: str | None
    has_push_token: bool
    last_seen_at: datetime
